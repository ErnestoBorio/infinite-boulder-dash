/**
 * Authentic Commodore 64 Boulder Dash PRNG
 * Advances the 16-bit LFSR/seed state and returns the next pseudo-random byte.
 * @param {[number, number]} seeds
 * @returns {number}
 */
export function bdrandom(seeds) {
  const tmp1 = (seeds[0] & 0x01) * 0x80;
  const tmp2 = (seeds[1] >> 1) & 0x7F;

  let result = seeds[1] + (seeds[1] & 0x01) * 0x80;
  let carry = result > 0xFF ? 1 : 0;
  result = (result & 0xFF) + carry + 0x13;
  carry = result > 0xFF ? 1 : 0;
  seeds[1] = result & 0xFF;

  result = seeds[0] + carry + tmp1;
  carry = result > 0xFF ? 1 : 0;
  result = (result & 0xFF) + carry + tmp2;
  seeds[0] = result & 0xFF;

  return seeds[0];
}

/**
 * Decodes a raw cave byte array into an expanded 40x22 grid and metadata.
 * @param {number} caveIndex - Index 0 to 19 (Cave A to Intermission 4)
 * @param {number} [difficulty=0] - Difficulty 0 to 4 (Level 1 to 5)
 */
export function decodeCave(caveIndex, difficulty = 0) {
  if (caveIndex < 0 || caveIndex >= RAW_CAVE_DATA.length) {
    throw new Error(`Invalid cave index: ${caveIndex}`);
  }
  difficulty = Math.max(0, Math.min(4, difficulty));

  const raw = RAW_CAVE_DATA[caveIndex];
  const width = 40;
  const height = 22;

  const color1 = C64_PALETTE[raw[0x13]] || C64_PALETTE[8];
  const color2 = C64_PALETTE[raw[0x14]] || C64_PALETTE[11];
  const color3 = C64_PALETTE[raw[0x15]] || C64_PALETTE[0];

  const randomObjects = [
    OBJECT_BY_CODE[raw[0x18]] || OBJECT.SPACE,
    OBJECT_BY_CODE[raw[0x19]] || OBJECT.BOULDER,
    OBJECT_BY_CODE[raw[0x1A]] || OBJECT.DIAMOND,
    OBJECT_BY_CODE[raw[0x1B]] || OBJECT.SPACE
  ];
  const randomObjectProb = [raw[0x1C], raw[0x1D], raw[0x1E], raw[0x1F]];

  // 2D grid: grid[y][x]
  const grid = Array.from({ length: height }, () =>
    Array.from({ length: width }, () => OBJECT.SPACE)
  );

  // Procedural random fill
  const seedVal = raw[0x04 + difficulty];
  const seeds = [0, seedVal];

  for (let y = 1; y < height - 1; y++) {
    for (let x = 0; x < width; x++) {
      let obj = OBJECT.DIRT;
      bdrandom(seeds);
      for (let n = 0; n < randomObjects.length; n++) {
        if (seeds[0] < randomObjectProb[n]) {
          obj = randomObjects[n];
        }
      }
      grid[y][x] = obj;
    }
  }

  // Perimeter steel wall
  for (let x = 0; x < width; x++) {
    grid[0][x] = OBJECT.STEELWALL;
    grid[height - 1][x] = OBJECT.STEELWALL;
  }
  for (let y = 0; y < height; y++) {
    grid[y][0] = OBJECT.STEELWALL;
    grid[y][width - 1] = OBJECT.STEELWALL;
  }

  // Helper drawing functions
  function drawSingle(obj, x, y) {
    if (x >= 0 && x < width && y >= 0 && y < height) {
      grid[y][x] = obj;
    }
  }

  function drawLine(obj, startX, startY, len, dir) {
    const dx = [ 0,  1, 1, 1, 0, -1, -1, -1 ][dir] ?? 0;
    const dy = [-1, -1, 0, 1, 1,  1,  0, -1 ][dir] ?? 0;
    let cx = startX;
    let cy = startY;
    for (let i = 0; i < len; i++) {
      drawSingle(obj, cx, cy);
      cx += dx;
      cy += dy;
    }
  }

  function drawRect(obj, startX, startY, w, h) {
    drawLine(obj, startX,         startY,         w, DIR.RIGHT);
    drawLine(obj, startX,         startY + h - 1, w, DIR.RIGHT);
    drawLine(obj, startX,         startY,         h, DIR.DOWN);
    drawLine(obj, startX + w - 1, startY,         h, DIR.DOWN);
  }

  function drawFilledRect(obj, startX, startY, w, h, fillObj) {
    drawRect(obj, startX, startY, w, h);
    for (let y = startY + 1; y < startY + h - 1; y++) {
      for (let x = startX + 1; x < startX + w - 1; x++) {
        drawSingle(fillObj, x, y);
      }
    }
  }

  // Overlay vector commands
  let offset = 0x20;
  while (offset < raw.length && raw[offset] !== 0xFF) {
    const b = raw[offset++];
    const objCode = b & 0x3F;
    const kind = (b >> 6) & 0x03;
    const obj = OBJECT_BY_CODE[objCode] || OBJECT.SPACE;

    const x = raw[offset++];
    const y = raw[offset++] - 2; // C64 coordinate offset (first 2 lines reserved for score)

    switch (kind) {
      case 0: // Single object
        drawSingle(obj, x, y);
        break;
      case 1: // Line
        drawLine(obj, x, y, raw[offset++], raw[offset++]);
        break;
      case 2: // Filled rectangle
        drawFilledRect(obj, x, y, raw[offset++], raw[offset++], OBJECT_BY_CODE[raw[offset++]] || OBJECT.DIRT);
        break;
      case 3: // Outline rectangle
        drawRect(obj, x, y, raw[offset++], raw[offset++]);
        break;
    }
  }

  return {
    index: caveIndex,
    name: CAVE_NAMES[caveIndex],
    description: CAVE_DESCRIPTIONS[caveIndex] || "",
    difficulty: difficulty + 1,
    width,
    height,
    magicWallTime: raw[0x01],
    amoebaTime: raw[0x01],
    diamondValue: raw[0x02],
    extraDiamondValue: raw[0x03],
    diamondsNeeded: raw[0x09 + difficulty],
    caveTime: raw[0x0E + difficulty],
    colors: {
      color1,
      color2,
      color3
    },
    grid
  };
}
